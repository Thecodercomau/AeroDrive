using AeroDrive.Core;
using AeroDrive.SaveSystem;
using UnityEngine;

namespace AeroDrive.Vehicles
{
    /// <summary>
    /// The garage: choosing which car to drive, which colour, and which cars are available.
    /// </summary>
    /// <remarks>
    /// Swapping a car at runtime is done by replacing the <see cref="VehicleConfig"/> on the existing
    /// <see cref="VehicleController"/> rather than by destroying and respawning a prefab. That works
    /// because everything about a car's handling lives in the config — mass, wheel geometry, engine —
    /// and it avoids the class of bug where a respawn loses the camera, the audio binding or the
    /// challenge's reference to the car.
    ///
    /// Where the visual body genuinely differs between cars, the optional prefab is instantiated
    /// under the body mount and the old one destroyed; the physics rig is never touched.
    /// </remarks>
    public sealed class GarageController : MonoBehaviour
    {
        [Header("Catalogue")]
        [Tooltip("Every car the player can own. Required.")]
        public VehicleCatalog catalog;

        [Header("Scene")]
        [Tooltip("The car that gets modified. Required.")]
        public VehicleController vehicle;

        [Tooltip("Where a car's visual body is parented when the prefab changes. Optional.")]
        public Transform bodyMount;

        [Tooltip("Renderers whose colour is set from the config's paint options.")]
        public Renderer[] paintRenderers = new Renderer[0];

        [Header("Preview")]
        [Tooltip("Turntable used by the garage camera. Optional.")]
        public Transform previewPivot;

        [Tooltip("Degrees per second the preview rotates.")]
        public float previewRotationSpeed = 18f;

        private EventBus _bus;
        private SaveManager _save;
        private MaterialPropertyBlock _paintProperties;
        private GameObject _currentBody;

        // The paint colour is the only shader property the garage writes, so it is looked up by name
        // rather than by a shared material asset that would be edited on disk.
        private static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");
        private static readonly int LegacyColorId = Shader.PropertyToID("_Color");

        /// <summary>Selected vehicle id. Assigning it applies the car.</summary>
        public string SelectedVehicleId { get; private set; }

        /// <summary>Index of the selected paint, into the selected config's paint options.</summary>
        public int SelectedPaintIndex { get; private set; }

        /// <summary>Give the garage its dependencies. Called by the session root.</summary>
        public void Initialise(EventBus bus, SaveManager save)
        {
            _bus = bus;
            _save = save;
        }

        private void Awake()
        {
            _paintProperties = new MaterialPropertyBlock();
        }

        private void Start()
        {
            if (catalog == null || vehicle == null) return;

            // Same fallback as the session: a scene generated by the editor wizard never calls
            // Initialise, and the garage cannot load the player's chosen car without the save file.
            if (_save == null && GameRoot.Instance != null) Initialise(GameRoot.Instance.Bus, GameRoot.Instance.Save);

            catalog.Validate();

            string wanted = _save != null ? _save.Data.progress.selectedVehicleId : null;
            if (string.IsNullOrEmpty(wanted) || !IsSelectable(wanted))
            {
                // The saved car is either missing from the catalogue or still locked — which happens
                // when a save is copied between builds. Falling back beats loading nothing.
                VehicleCatalogEntry fallback = catalog.FirstUnlocked();
                wanted = fallback != null ? fallback.VehicleId : string.Empty;
            }

            SelectVehicle(wanted);
        }

        private void Update()
        {
            if (previewPivot == null) return;
            previewPivot.Rotate(Vector3.up, previewRotationSpeed * Time.deltaTime, Space.World);
        }

        /// <summary>True when the player owns this car.</summary>
        public bool IsUnlocked(string vehicleId)
        {
            if (string.IsNullOrEmpty(vehicleId)) return false;

            VehicleCatalogEntry entry = catalog != null ? catalog.Find(vehicleId) : null;
            if (entry == null) return false;
            if (!entry.requiresUnlock) return true;

            return _save != null && _save.IsVehicleUnlocked(vehicleId);
        }

        /// <summary>True when the car exists and can be driven right now.</summary>
        public bool IsSelectable(string vehicleId)
        {
            return catalog != null && catalog.Find(vehicleId) != null && IsUnlocked(vehicleId);
        }

        /// <summary>
        /// Unlock a car, which is what finishing a challenge does.
        /// </summary>
        /// <returns>True when this unlocked something new.</returns>
        public bool UnlockVehicle(string vehicleId)
        {
            if (_save == null || string.IsNullOrEmpty(vehicleId)) return false;

            bool unlocked = _save.UnlockVehicle(vehicleId);
            if (unlocked)
            {
                _save.Save();
                VehicleCatalogEntry entry = catalog != null ? catalog.Find(vehicleId) : null;
                if (entry != null) Debug.Log($"[AeroDrive] Unlocked {entry.DisplayName}");
            }

            return unlocked;
        }

        /// <summary>
        /// Switch the player's car.
        /// </summary>
        /// <returns>True when the car changed.</returns>
        /// <remarks>
        /// Refuses to select a locked car instead of throwing: the id can come from a save file, and
        /// an invalid one is a data problem, not a programming error.
        /// </remarks>
        public bool SelectVehicle(string vehicleId)
        {
            if (catalog == null || vehicle == null) return false;

            VehicleCatalogEntry entry = catalog.Find(vehicleId);
            if (entry == null)
            {
                Debug.LogWarning($"[AeroDrive] No vehicle \"{vehicleId}\" in the catalog.");
                return false;
            }

            if (!IsUnlocked(vehicleId))
            {
                Debug.Log($"[AeroDrive] {entry.DisplayName} is still locked.");
                return false;
            }

            SelectedVehicleId = vehicleId;
            SelectedPaintIndex = Mathf.Clamp(SelectedPaintIndex, 0, Mathf.Max(0, entry.config.paintOptions.Length - 1));

            vehicle.config = entry.config;
            vehicle.ApplyConfig();
            ApplyBody(entry);
            ApplyPaint(entry.config);

            if (_save != null)
            {
                _save.Data.progress.selectedVehicleId = vehicleId;
                _save.MarkDirty();
            }

            return true;
        }

        /// <summary>Step forward or back through the catalog's unlocked cars.</summary>
        public bool CycleVehicle(int direction)
        {
            if (catalog == null || catalog.Count == 0) return false;

            int start = Mathf.Max(0, catalog.IndexOf(SelectedVehicleId));

            // Bounded by the catalog size, so a catalogue whose every entry is locked cannot spin.
            for (int step = 1; step <= catalog.Count; step++)
            {
                int index = ((start + direction * step) % catalog.Count + catalog.Count) % catalog.Count;
                VehicleCatalogEntry candidate = catalog.entries[index];
                if (candidate == null || !IsUnlocked(candidate.VehicleId)) continue;

                return SelectVehicle(candidate.VehicleId);
            }

            return false;
        }

        /// <summary>Step through the current car's paint options.</summary>
        public bool CyclePaint(int direction)
        {
            VehicleCatalogEntry entry = catalog != null ? catalog.Find(SelectedVehicleId) : null;
            if (entry == null || entry.config.paintOptions == null || entry.config.paintOptions.Length == 0) return false;

            int count = entry.config.paintOptions.Length;
            SelectedPaintIndex = ((SelectedPaintIndex + direction) % count + count) % count;

            ApplyPaint(entry.config);
            return true;
        }

        /// <summary>Replace the visual body with the entry's prefab, if it has one.</summary>
        private void ApplyBody(VehicleCatalogEntry entry)
        {
            if (bodyMount == null || entry.prefab == null) return;

            if (_currentBody != null) Destroy(_currentBody);

            // The prefab is parented and reset so its own transform cannot offset the car, which
            // would break the wheel alignment solved from the config.
            _currentBody = Instantiate(entry.prefab, bodyMount);
            _currentBody.transform.localPosition = Vector3.zero;
            _currentBody.transform.localRotation = Quaternion.identity;
            _currentBody.name = "Body";
        }

        /// <summary>
        /// Paint every renderer with the selected colour.
        /// </summary>
        /// <remarks>
        /// Uses a <see cref="MaterialPropertyBlock"/> rather than assigning a new material, so the
        /// paint never mutates the shared material asset — which would repaint every car in the
        /// scene and, in the editor, dirty the material on disk.
        /// </remarks>
        public void ApplyPaint(VehicleConfig config)
        {
            if (config == null || paintRenderers == null || paintRenderers.Length == 0) return;

            Color color = config.paintOptions[Mathf.Clamp(SelectedPaintIndex, 0, config.paintOptions.Length - 1)];
            if (_paintProperties == null) _paintProperties = new MaterialPropertyBlock();

            for (int i = 0; i < paintRenderers.Length; i++)
            {
                Renderer renderer = paintRenderers[i];
                if (renderer == null) continue;

                renderer.GetPropertyBlock(_paintProperties);

                // Both names are set: URP and the built-in pipeline call the base colour different
                // things, and a property block with an unknown name is simply ignored.
                _paintProperties.SetColor(BaseColorId, color);
                _paintProperties.SetColor(LegacyColorId, color);

                renderer.SetPropertyBlock(_paintProperties);
            }
        }

        /// <summary>Repair the car, as a garage would. Free, because this is not a racing game.</summary>
        public void RepairVehicle()
        {
            vehicle?.RepairFully();
        }
    }
}
