using AeroDrive.Input;
using AeroDrive.Presentation;
using AeroDrive.SaveSystem;
using AeroDrive.Vehicles;
using UnityEngine;

namespace AeroDrive.Core
{
    /// <summary>
    /// Owns one driving session: the car, the input, the camera and the pause state.
    /// </summary>
    /// <remarks>
    /// A session is the unit that starts when the player leaves the menu and ends when they go back,
    /// so everything that must be reset between sessions lives here and nothing survives by accident.
    ///
    /// Pausing is handled by setting <see cref="Time.timeScale"/> to zero, which stops the physics
    /// and every <c>Update</c> that uses scaled time — and by explicitly disabling input, because an
    /// analogue throttle that keeps integrating while the game is frozen would otherwise resume at
    /// full power.
    /// </remarks>
    public sealed class SessionController : MonoBehaviour
    {
        [Header("Scene references")]
        [Tooltip("The car the player drives. Required.")]
        public VehicleController vehicle;

        public ChaseCamera chaseCamera;
        public Hud hud;

        [Tooltip("Engine, tyre and wind audio, driven from the car.")]
        public EngineAudio audioRig;

        [Tooltip("Shown while the game is paused. Optional.")]
        public GameObject pauseMenu;

        [Tooltip("Shown when the map's loading screen should be hidden. Optional.")]
        public GameObject loadingScreen;

        [Tooltip("Where the player starts. Falls back to the car's current position.")]
        public Transform spawnPoint;

        [Header("Behaviour")]
        [Tooltip("Start with the pause menu open. Useful for a menu-driven scene.")]
        public bool startPaused;

        [Tooltip("Seconds of play time between save writes. Zero disables periodic saving.")]
        [Range(0f, 600f)]
        public float autosaveInterval = 120f;

        private EventBus _bus;
        private SaveManager _save;
        private VehicleInput _input;
        private GameSettings _settings;

        private bool _paused;
        private bool _sessionActive;
        private float _sessionSeconds;
        private float _autosaveTimer;
        private float _totalPlaySeconds;

        /// <summary>True while the game is paused.</summary>
        public bool IsPaused
        {
            get { return _paused; }
        }

        /// <summary>Seconds the current session has been running, excluding paused time.</summary>
        public float SessionSeconds
        {
            get { return _sessionSeconds; }
        }

        /// <summary>The input source, exposed so an AI or a test can take the wheel.</summary>
        public IVehicleInputSource InputSource
        {
            get { return _input; }
        }

        /// <summary>Wire the session up. Called by <see cref="GameRoot"/> once the save is loaded.</summary>
        public void Initialise(EventBus bus, SaveManager save)
        {
            _bus = bus;
            _save = save;
            _settings = save != null ? save.Data.settings : GameSettings.CreateDefault();
        }

        private void Start()
        {
            StartSession();
        }

        /// <summary>Begin a session: spawn the car, build the input, bind the presentation.</summary>
        public void StartSession()
        {
            if (vehicle == null)
            {
                Debug.LogError("[AeroDrive] SessionController has no vehicle assigned.", this);
                enabled = false;
                return;
            }

            // Fall back to the root's bus and save file when nobody wired the session explicitly.
            // A scene generated by the editor wizard has no chance to call Initialise, and a
            // session with no save file would silently stop recording progress.
            if (_save == null && GameRoot.Instance != null) Initialise(GameRoot.Instance.Bus, GameRoot.Instance.Save);

            _settings = _settings ?? GameSettings.CreateDefault();

            _input = new VehicleInput(_settings);
            vehicle.SetInputSource(_input);

            if (spawnPoint != null)
            {
                vehicle.transform.SetPositionAndRotation(spawnPoint.position, spawnPoint.rotation);
                vehicle.SetSpawnPoint(spawnPoint.position, spawnPoint.rotation);
            }

            if (chaseCamera != null)
            {
                chaseCamera.target = vehicle;
                chaseCamera.SnapToTarget();
            }

            if (hud != null) hud.Bind(vehicle, chaseCamera);
            if (audioRig != null) audioRig.Bind(vehicle, _bus);

            SetActive(loadingScreen, false);
            SetPaused(startPaused);

            _sessionActive = true;
            _sessionSeconds = 0f;
            _autosaveTimer = 0f;

            _bus?.Publish(new GameEvents.SessionStarted(
                vehicle.Config != null ? vehicle.Config.vehicleId : "unknown",
                gameObject.scene.name));
        }

        private void Update()
        {
            if (!_sessionActive) return;

            GatherCommands();

            if (_paused) return;

            _sessionSeconds += Time.deltaTime;
            TickAutosave();

            if (hud != null && _input != null) hud.SetGamepadConnected(_input.GamepadConnected);
        }

        /// <summary>
        /// Read the actions that are not the car's business: pause, camera, headlights, recovery.
        /// </summary>
        /// <remarks>
        /// These are polled rather than routed through the vehicle because they act on the session,
        /// not on the car, and the vehicle controller should not know that a pause menu exists.
        /// </remarks>
        private void GatherCommands()
        {
            if (_input == null) return;

            // Pause is read from the keyboard directly, because the vehicle input is disabled while
            // paused and would otherwise never report the key that un-pauses the game.
            if (_input.Keyboard != null && WasPausePressed())
            {
                SetPaused(!_paused);
                return;
            }

            if (_paused) return;

            VehicleInputState state = _input.Read(Time.deltaTime);

            if (state.toggleCamera && chaseCamera != null)
            {
                CameraMode mode = chaseCamera.CycleMode();
                hud?.ShowMessage(mode.ToString() + " camera", 1.5f);
            }

            if (state.recover)
            {
                vehicle.Recover();
                hud?.ShowMessage("Vehicle recovered", 1.5f);
            }

            if (state.toggleHeadlights)
            {
                _headlightsOn = !_headlightsOn;
                vehicle.SetHeadlights(_headlightsOn);
            }
        }

        private bool _headlightsOn;

        private bool WasPausePressed()
        {
            string[] names = InputBindings.KeysFor(_settings.bindings, InputBindings.Pause);
            for (int i = 0; i < names.Length; i++)
            {
                if (System.Enum.TryParse(names[i], out KeyCode key) && UnityEngine.Input.GetKeyDown(key))
                {
                    return true;
                }
            }

            // Escape always pauses, even when the player has rebound the action to something else.
            // Being unable to pause is worse than having two keys that pause.
            return UnityEngine.Input.GetKeyDown(KeyCode.Escape);
        }

        /// <summary>Pause or resume, applying it to time, input and audio together.</summary>
        public void SetPaused(bool paused)
        {
            _paused = paused;
            Time.timeScale = paused ? 0f : 1f;

            if (_input != null) _input.Enabled = !paused;
            audioRig?.SetMuted(paused);

            SetActive(pauseMenu, paused);
            Cursor.visible = paused;
            Cursor.lockState = paused ? CursorLockMode.None : CursorLockMode.Confined;
        }

        /// <summary>
        /// End the session, banking play time and writing the save.
        /// </summary>
        /// <remarks>
        /// Always resumed first: quitting while paused would leave <see cref="Time.timeScale"/> at
        /// zero, and the main menu would appear to be frozen.
        /// </remarks>
        public void EndSession()
        {
            if (!_sessionActive) return;

            if (_paused) SetPaused(false);

            _sessionActive = false;
            FlushPlayTime();

            _bus?.Publish(new GameEvents.SessionEnded(_sessionSeconds));
        }

        private void TickAutosave()
        {
            if (autosaveInterval <= 0f || _save == null) return;

            _autosaveTimer += Time.deltaTime;
            if (_autosaveTimer < autosaveInterval) return;

            _autosaveTimer = 0f;
            FlushPlayTime();
            _save.Save();
        }

        /// <summary>Add the un-banked play time to the save file and mark it dirty.</summary>
        private void FlushPlayTime()
        {
            if (_save == null) return;

            float unbanked = _sessionSeconds - _totalPlaySeconds;
            if (unbanked <= 0f) return;

            _save.AddPlayTime(unbanked);
            _totalPlaySeconds = _sessionSeconds;
        }

        private void OnApplicationPause(bool paused)
        {
            // Mobile and console suspend the app rather than closing it, so this is the last reliable
            // moment to put progress on disk.
            if (!paused) return;

            FlushPlayTime();
            _save?.Save();
        }

        private void OnApplicationQuit()
        {
            FlushPlayTime();
            _save?.Save();
        }

        private void OnDestroy()
        {
            // A scene change must not leave the game frozen or muted.
            if (_paused) SetPaused(false);
        }

        private static void SetActive(GameObject target, bool active)
        {
            if (target != null && target.activeSelf != active) target.SetActive(active);
        }
    }
}
